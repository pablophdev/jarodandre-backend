CREATE SCHEMA catalogo;
CREATE TABLE catalogo.categorias (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 5) PRIMARY KEY,
    nombre varchar(100) NOT NULL UNIQUE,
    slug varchar(120) NOT NULL UNIQUE
);
CREATE TABLE catalogo.productos (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 15) PRIMARY KEY,
    categoria_id bigint NOT NULL REFERENCES catalogo.categorias(id),
    nombre varchar(180) NOT NULL,
    descripcion text NOT NULL,
    precio_clp bigint NOT NULL CHECK (precio_clp >= 0),
    imagen_key varchar(500) NOT NULL,
    etiquetas varchar array NOT NULL,
    grupo varchar(20) NOT NULL CHECK (grupo IN ('new','popular')),
    insignia varchar(80) NOT NULL,
    destacado boolean NOT NULL,
    valoracion integer NOT NULL CHECK (valoracion BETWEEN 0 AND 5),
    cantidad_resenas integer NOT NULL CHECK (cantidad_resenas >= 0),
    disponibilidad varchar(20) NOT NULL CHECK (disponibilidad IN ('DISPONIBLE','AGOTADO','CONSULTAR')),
    archivado_en timestamp with time zone,
    creado_en timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    actualizado_en timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);
CREATE INDEX idx_productos_categoria ON catalogo.productos(categoria_id, archivado_en);
CREATE TABLE catalogo.publicaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY,
    slug varchar(180) NOT NULL UNIQUE,
    titulo varchar(250) NOT NULL,
    autor_visible varchar(120) NOT NULL,
    parrafos varchar array NOT NULL,
    portada_key varchar(500) NOT NULL,
    estado varchar(20) NOT NULL CHECK (estado IN ('BORRADOR','PUBLICADO')),
    publicado_en timestamp with time zone,
    creado_en timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    actualizado_en timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    CHECK (estado <> 'PUBLICADO' OR (publicado_en IS NOT NULL AND cardinality(parrafos) > 0))
);
CREATE INDEX idx_publicaciones_estado_fecha ON catalogo.publicaciones(estado, publicado_en);
